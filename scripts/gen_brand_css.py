#!/usr/bin/env python3
"""Generate static/css/brand.css from the PartOut app theme.

The single source of truth for the brand palette is
``partout-app/lib/config/theme.dart`` (SPEC section 14). Retyping its values
into a stylesheet is how drift happens, so this script parses the Dart
constants and emits CSS custom properties instead. CI runs ``--check``: if
theme.dart moved and brand.css did not, the build fails.

Usage:
    scripts/gen_brand_css.py          # write static/css/brand.css
    scripts/gen_brand_css.py --check  # exit 1 on drift, print diff
"""

from __future__ import annotations

import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT.parent / "partout-app" / "lib" / "config" / "theme.dart"
OUT = ROOT / "static" / "css" / "brand.css"

# `static const Color <name> = Color(0xFFRRGGBB);`
CONST_RE = re.compile(
    r"static\s+const\s+Color\s+(\w+)\s*=\s*Color\(\s*0x([0-9A-Fa-f]{8})\s*\)"
)

# Colors that live inline in the dark ColorScheme literal rather than as named
# constants. Pinned here with their source line so the dependency is legible;
# --check still catches every named constant above.
EXTRA = {
    # darkScheme `onPrimary`
    "darkOnPrimary": "0A0F06",
    # darkScheme `onPrimaryContainer`
    "darkOnPrimaryContainer": "D9FFB0",
    # darkScheme `tertiary` (the brand gold)
    "darkTertiary": "E4C46B",
}


def kebab(name: str) -> str:
    out = []
    for i, ch in enumerate(name):
        if ch.isupper() and i and not name[i - 1].isupper():
            out.append("-")
        out.append(ch.lower())
    return "".join(out)


def colors_from_dart(text: str) -> dict[str, str]:
    found = {}
    for m in CONST_RE.finditer(text):
        argb = m.group(2).upper()
        if argb[:2] != "FF":
            continue  # non-opaque color: not part of the brand surface ramp
        found[m.group(1)] = argb[2:]
    found.update(EXTRA)
    return found


def render(colors: dict[str, str]) -> str:
    lines = [
        "/* GENERATED by scripts/gen_brand_css.py from "
        "partout-app/lib/config/theme.dart.",
        "   Do not edit by hand: change the Dart theme, then re-run the script.",
        "   --check in CI fails if the two disagree. */",
        ":root {",
    ]
    for name, hexval in colors.items():
        lines.append(f"  --{kebab(name)}: #{hexval};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    if not THEME.exists():
        print(f"error: theme source not found: {THEME}", file=sys.stderr)
        return 2
    generated = render(colors_from_dart(THEME.read_text()))

    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current == generated:
            print("brand.css is current")
            return 0
        sys.stdout.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile=str(OUT),
                tofile="regenerated",
            )
        )
        print("error: brand.css is stale — run scripts/gen_brand_css.py", file=sys.stderr)
        return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generated)
    print(f"wrote {OUT} ({len(colors_from_dart(THEME.read_text()))} colors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
